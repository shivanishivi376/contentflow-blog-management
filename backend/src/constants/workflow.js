import { BLOG_STATUS } from './blogStatus.js';

export const WORKFLOW_ACTIONS = {
  START_WRITING: 'START_WRITING',
  SUBMIT_FOR_REVIEW: 'SUBMIT_FOR_REVIEW',
  APPROVE: 'APPROVE',
  REJECT: 'REJECT',
  RESUME_WRITING: 'RESUME_WRITING',
  PUBLISH_SUCCESS: 'PUBLISH_SUCCESS',
  PUBLISH_FAIL: 'PUBLISH_FAIL',
  RETRY: 'RETRY'
};

export const TRANSITIONS = {
  [BLOG_STATUS.DRAFT]: {
    [WORKFLOW_ACTIONS.START_WRITING]: BLOG_STATUS.IN_WRITING
  },
  [BLOG_STATUS.IN_WRITING]: {
    [WORKFLOW_ACTIONS.SUBMIT_FOR_REVIEW]: BLOG_STATUS.IN_REVIEW
  },
  [BLOG_STATUS.IN_REVIEW]: {
    [WORKFLOW_ACTIONS.APPROVE]: BLOG_STATUS.IN_PUBLISHING,
    [WORKFLOW_ACTIONS.REJECT]: BLOG_STATUS.RE_ASSIGN
  },
  [BLOG_STATUS.RE_ASSIGN]: {
    [WORKFLOW_ACTIONS.RESUME_WRITING]: BLOG_STATUS.IN_WRITING
  },
  [BLOG_STATUS.IN_PUBLISHING]: {
    [WORKFLOW_ACTIONS.PUBLISH_SUCCESS]: BLOG_STATUS.PUBLISHED,
    [WORKFLOW_ACTIONS.PUBLISH_FAIL]: BLOG_STATUS.PUBLISH_FAILED
  },
  [BLOG_STATUS.PUBLISH_FAILED]: {
    [WORKFLOW_ACTIONS.RETRY]: BLOG_STATUS.IN_PUBLISHING
  }
};

export function transition(currentStatus, action) {
  const next = TRANSITIONS[currentStatus]?.[action];
  if (!next) {
    throw new Error(`Invalid transition: ${action} from status ${currentStatus}`);
  }
  return next;
}

export const ALLOWED_TRANSITIONS = {
  [BLOG_STATUS.DRAFT]: [BLOG_STATUS.IN_WRITING, BLOG_STATUS.IN_REVIEW],
  [BLOG_STATUS.IN_WRITING]: [BLOG_STATUS.IN_REVIEW, BLOG_STATUS.DRAFT],
  [BLOG_STATUS.IN_REVIEW]: [BLOG_STATUS.RE_ASSIGN, BLOG_STATUS.IN_PUBLISHING, BLOG_STATUS.IN_WRITING],
  [BLOG_STATUS.RE_ASSIGN]: [BLOG_STATUS.IN_WRITING],
  [BLOG_STATUS.IN_PUBLISHING]: [BLOG_STATUS.PUBLISHED, BLOG_STATUS.PUBLISH_FAILED, BLOG_STATUS.IN_REVIEW],
  [BLOG_STATUS.PUBLISH_FAILED]: [BLOG_STATUS.IN_PUBLISHING, BLOG_STATUS.DRAFT],
  [BLOG_STATUS.PUBLISHED]: [BLOG_STATUS.DRAFT]
};

export const isValidTransition = (currentStatus, targetStatus) => {
  if (currentStatus === targetStatus) return true;
  const allowed = ALLOWED_TRANSITIONS[currentStatus] || [];
  return allowed.includes(targetStatus);
};

